//! Live evals: run aster against fixed cases and compare models, where
//! [`crate::turn`] can only grade sessions that already happened. Ori owns the
//! running, so cases live here and render to the `*.eval.ts` it insists on.

use std::path::{Path, PathBuf};
use std::process::Command;

use anyhow::{Context, Result, bail};
use serde::{Deserialize, Serialize};

const GENERATED: &str = "cases.eval.ts";

/// One thing a model has to get right, and the tool budget it gets.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct Case {
    pub name: String,
    pub prompt: String,
    #[serde(default)]
    pub must_mention: Option<String>,
    #[serde(default)]
    pub calls: Vec<String>,
    #[serde(default)]
    pub avoids: Vec<String>,
    #[serde(default)]
    pub at_most: Vec<(String, usize)>,
}

/// The cases shipped with aster. Each encodes a harness fix, so a regression in
/// that fix fails an eval rather than going unnoticed until the next report.
pub fn default_cases() -> Vec<Case> {
    vec![
        Case {
            name: "reaches a gitignored directory".into(),
            prompt: "What activation events does the vscode extension in this repo declare? \
                     Answer from its package.json."
                .into(),
            must_mention: Some("activation".into()),
            calls: Vec::new(),
            avoids: vec!["edit_file".into()],
            // `editors/` is gitignored. Before the ignore fallback every
            // discovery tool came back empty and the model kept guessing, at
            // nine calls and still wrong. Observed runs land between one and
            // three, so the ceiling sits above the noise and still catches a
            // return to flailing.
            at_most: vec![("find_files".into(), 5)],
        },
        Case {
            name: "does not re-run an identical search".into(),
            prompt: "Which function in crates/aster-tools decides whether a directory is \
                     skipped? Name it and the file it lives in."
                .into(),
            must_mention: Some("is_skipped".into()),
            calls: Vec::new(),
            avoids: vec!["edit_file".into()],
            at_most: vec![("search_files".into(), 3)],
        },
        Case {
            name: "batches lookups into one round".into(),
            prompt: "Compare how find.rs and list.rs in crates/aster-tools handle .gitignore. \
                     Read both before answering."
                .into(),
            must_mention: None,
            calls: Vec::new(),
            avoids: vec!["edit_file".into()],
            at_most: vec![("read_file".into(), 3)],
        },
    ]
}

/// Render the cases as an Ori eval file.
pub fn render_eval(cases: &[Case], model: Option<&str>) -> String {
    let setup = match model {
        Some(model) => format!("setupAgent({{ model: {} }})", quote(model)),
        None => "setupAgent()".into(),
    };
    let mut out = String::from(
        "// Generated by `aster-eval live`. Edit crates/aster-eval/src/live.rs instead.\n\
         import { expect, test } from \"bun:test\";\n\
         import { setupAgent } from \"ori/eval\";\n\n",
    );
    out.push_str(&format!("const agent = {setup};\n\n"));
    out.push_str(
        "const count = (run: { toolCalls: readonly unknown[] }, tool: string) =>\n  \
         run.toolCalls.filter((c) => (typeof c === \"string\" ? c : (c as any)?.name) === tool)\n    \
         .length;\n\n",
    );

    for case in cases {
        out.push_str(&format!(
            "test({}, async () => {{\n  const run = await agent.run({});\n",
            quote(&case.name),
            quote(&case.prompt)
        ));
        for tool in &case.calls {
            out.push_str(&format!("  run.tool({}).toBeCalled();\n", quote(tool)));
        }
        for tool in &case.avoids {
            out.push_str(&format!("  run.tool({}).toNotBeCalled();\n", quote(tool)));
        }
        for (tool, cap) in &case.at_most {
            out.push_str(&format!(
                "  expect(count(run, {})).toBeLessThanOrEqual({cap});\n",
                quote(tool)
            ));
        }
        if let Some(text) = &case.must_mention {
            out.push_str(&format!("  run.toMention({});\n", quote(text)));
        }
        out.push_str("  run.toComplete();\n});\n\n");
    }
    out
}

/// What one case did: enough to see why it passed or failed without going back
/// to the raw report.
#[derive(Debug, Clone)]
pub struct Outcome {
    pub case: String,
    pub passed: bool,
    pub tools: Vec<String>,
    pub secs: f64,
    pub cost_usd: Option<f64>,
    pub wrong_harness: Option<String>,
}

impl Outcome {
    /// `find_files×2 read_file×1`, in first-call order.
    pub fn tool_summary(&self) -> String {
        let mut order: Vec<&String> = Vec::new();
        for tool in &self.tools {
            if !order.contains(&tool) {
                order.push(tool);
            }
        }
        order
            .iter()
            .map(|tool| {
                let n = self.tools.iter().filter(|t| *t == *tool).count();
                format!("{tool}×{n}")
            })
            .collect::<Vec<_>>()
            .join(" ")
    }
}

#[derive(Debug, Clone)]
pub struct ModelRun {
    pub model: String,
    pub outcomes: Vec<Outcome>,
}

impl ModelRun {
    pub fn passed(&self) -> usize {
        self.outcomes.iter().filter(|o| o.passed).count()
    }

    pub fn failed(&self) -> usize {
        self.outcomes.len() - self.passed()
    }

    pub fn ok(&self) -> bool {
        self.failed() == 0 && !self.outcomes.is_empty()
    }

    /// Total tool calls across every case: the round count that decides how
    /// slow and expensive a model feels, independent of whether it passed.
    pub fn calls(&self) -> usize {
        self.outcomes.iter().map(|o| o.tools.len()).sum()
    }

    pub fn secs(&self) -> f64 {
        self.outcomes.iter().map(|o| o.secs).sum()
    }

    /// `None` when no case reported usage, so an unpriced model is never shown
    /// as the cheap one.
    pub fn cost_usd(&self) -> Option<f64> {
        let priced: Vec<f64> = self.outcomes.iter().filter_map(|o| o.cost_usd).collect();
        (!priced.is_empty()).then(|| priced.iter().sum())
    }
}

/// Write the generated eval into `dir`, run `ori eval --json` over it, and read
/// the result back. `dir` is the eval workspace, `repo` the checkout aster runs
/// against.
pub fn run_model(dir: &Path, repo: &Path, cases: &[Case], model: Option<&str>) -> Result<ModelRun> {
    let file = dir.join(GENERATED);
    std::fs::write(&file, render_eval(cases, model))
        .with_context(|| format!("writing {}", file.display()))?;

    eprintln!(
        "running {} case(s) against {} in {} — ori's progress follows",
        cases.len(),
        model.unwrap_or("the configured model"),
        repo.display()
    );
    // Ori narrates to stderr and only prints JSON at the end. Inheriting it is
    // the difference between watching the run and staring at nothing for
    // several minutes.
    let output = Command::new(ori_bin())
        .args(["eval", "--json", "--no-history"])
        .arg(GENERATED)
        .current_dir(dir)
        .env("ASTER_EVAL_REPO", repo)
        .stderr(std::process::Stdio::inherit())
        .output()
        .context("running `ori eval`; install it from openrouter.ai/labs/ori")?;

    let stdout = String::from_utf8_lossy(&output.stdout);
    let report: serde_json::Value = serde_json::from_str(stdout.trim())
        .with_context(|| format!("`ori eval` did not return JSON: {}", "see ori output above"))?;
    Ok(summarise(model.unwrap_or("(configured)"), &report))
}

const HARNESS: &str = "aster";

fn summarise(model: &str, report: &serde_json::Value) -> ModelRun {
    let array = |key: &str| {
        report
            .pointer(&format!("/data/{key}"))
            .and_then(|t| t.as_array())
            .cloned()
            .unwrap_or_default()
    };
    let tests = array("tests");
    let results = array("results");

    let outcomes = tests
        .iter()
        .enumerate()
        .map(|(i, test)| {
            let result = results.get(i);
            let harness = result
                .and_then(|r| r.pointer("/terminal/harness"))
                .and_then(|h| h.as_str())
                .unwrap_or("unknown");
            let tools = result
                .and_then(|r| r.get("toolCalls"))
                .and_then(|t| t.as_array())
                .map(|calls| {
                    calls
                        .iter()
                        .filter_map(|c| c.as_str().map(str::to_string))
                        .collect()
                })
                .unwrap_or_default();
            Outcome {
                case: test
                    .get("name")
                    .and_then(|n| n.as_str())
                    .unwrap_or("<unnamed>")
                    .to_string(),
                // A run against Ori's own agent proves nothing about this
                // harness, so it never counts as a pass however green it came
                // back.
                passed: test.get("status").and_then(|s| s.as_str()) == Some("pass")
                    && harness == HARNESS,
                tools,
                secs: test
                    .get("durationMs")
                    .and_then(|d| d.as_f64())
                    .unwrap_or_default()
                    / 1000.0,
                cost_usd: result
                    .and_then(|r| r.pointer("/terminal/payload/usage/costUsd"))
                    .and_then(|c| c.as_f64()),
                wrong_harness: (harness != HARNESS).then(|| harness.to_string()),
            }
        })
        .collect();

    ModelRun {
        model: model.to_string(),
        outcomes,
    }
}

/// Run every model in turn. Sequential on purpose: a parallel sweep would have
/// models competing for the same checkout and skew every timing.
pub fn sweep(dir: &Path, repo: &Path, cases: &[Case], models: &[String]) -> Result<Vec<ModelRun>> {
    if cases.is_empty() {
        bail!("no cases to run");
    }
    if models.is_empty() {
        return Ok(vec![run_model(dir, repo, cases, None)?]);
    }
    models
        .iter()
        .map(|model| run_model(dir, repo, cases, Some(model)))
        .collect()
}

/// Per-case detail first, then one summary row per model. The tool column is
/// the point: a case can pass and still show the round count creeping up.
pub fn render_live(runs: &[ModelRun]) -> String {
    if runs.is_empty() {
        return "no models run\n".into();
    }
    let mut out = String::new();
    for run in runs {
        out.push_str(&format!("\n{}\n", run.model));
        if run.outcomes.is_empty() {
            out.push_str("  (ori reported no cases; check its output above)\n");
            continue;
        }
        let width = run
            .outcomes
            .iter()
            .map(|o| o.case.len())
            .max()
            .unwrap_or(0)
            .max(4);
        for outcome in &run.outcomes {
            out.push_str(&format!(
                "  {} {:<width$}  {:>6.1}s  {}\n",
                if outcome.passed { "pass" } else { "FAIL" },
                outcome.case,
                outcome.secs,
                outcome.tool_summary()
            ));
            if let Some(harness) = &outcome.wrong_harness {
                out.push_str(&format!(
                    "       ran against harness {harness:?}, not {HARNESS:?}; the feature \
                     failed to boot, check `ori features validate`\n"
                ));
            }
        }
    }

    let width = runs.iter().map(|r| r.model.len()).max().unwrap_or(5).max(5);
    out.push_str(&format!(
        "\n{:<width$}  pass  fail  calls     wall      cost\n",
        "model"
    ));
    for run in runs {
        let cost = match run.cost_usd() {
            Some(cost) => format!("${cost:.4}"),
            None => "     ?".into(),
        };
        out.push_str(&format!(
            "{:<width$}  {:>4}  {:>4}  {:>5}  {:>6.1}s  {:>8}\n",
            run.model,
            run.passed(),
            run.failed(),
            run.calls(),
            run.secs(),
            cost
        ));
    }

    // Cheapest correct model, which is the question a sweep is asked to answer.
    if runs.len() > 1
        && let Some(best) = runs
            .iter()
            .filter(|r| r.ok())
            .min_by_key(|r| (r.calls(), (r.secs() * 1000.0) as u64))
    {
        out.push_str(&format!(
            "\nfewest calls with every case passing: {}\n",
            best.model
        ));
    }

    if runs.iter().any(|r| r.failed() > 0) {
        out.push_str("\nAssertion messages are in ori's output above.\n");
    }
    out
}

/// The checkout the cases are written against: the enclosing git worktree, not the
/// current directory. The eval workspace lives inside the repo, so running from
/// there would point aster at `crates/aster-eval/evals` and fail every case.
pub fn repo_root(from: &Path) -> PathBuf {
    from.ancestors()
        .find(|dir| dir.join(".git").exists())
        .unwrap_or(from)
        .to_path_buf()
}

fn ori_bin() -> PathBuf {
    if let Ok(path) = std::env::var("ORI_BIN") {
        return path.into();
    }
    let local = PathBuf::from(std::env::var("HOME").unwrap_or_default()).join(".local/bin/ori");
    if local.exists() { local } else { "ori".into() }
}

fn quote(text: &str) -> String {
    serde_json::to_string(text).unwrap_or_else(|_| "\"\"".into())
}

